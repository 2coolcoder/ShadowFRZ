"""Rebuild clean, dependency-ordered job files from the config.json of every finished run.

    python scripts/export_jobs.py            # writes jobs/final/*.txt

Stages (run in order; each file is a valid input for scripts/queue.py):
  1_trackA.txt            DDG / backprop on CIFAR ResNets
  2_trackC_lr.txt         BERT learning-rate sweeps (Post-LN 4k proxies, Pre-LN 5k-step stops)
  3_trackB.txt            ResNet-50 variants (except random replay)
  4_trackC.txt            BERT ladder, ablations, seeds, depth sweep (except random replay)
  5_random_replay.txt     row-7 controls; need the matching `full_s0` trace from stages 3/4
  6_finetune.txt          SST-2 downstream of stage-4 checkpoints + public-checkpoint fine-tunes
  7_postln_edge.txt       optional: archived Post-LN / edge-of-stability runs (stopped by hand at
                          ~6.5-7k steps; regenerated with --stop_at 7000)
Runs named *_1bw_warm10_* are skipped: they came from a since-fixed bug (1BW kept its
shadow for the first 10% of training) and cannot be regenerated by the current code.
"""
import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "jobs", "final")
SCRIPT = {"trackA": "train_ddg.py", "trackB": "train_cnn.py", "trackC": "train_bert.py",
          "trackC_lr": "train_bert.py", "trackC_sweep": "train_bert.py", "trackC_edge": "train_bert.py",
          "trackC_ft": "finetune_glue.py", "trackC_pub": "finetune_glue.py"}


def cli(cfg, track, out):
    args = []
    for k, v in cfg.items():
        if k in ("out",) or v is None or v is False:
            continue
        if k == "recipe_cfg" or k in ("bounds", "n_units"):          # derived, written by train_ddg
            continue
        args.append(f"--{k}" if v is True else f"--{k} {v}")
    if SCRIPT[track] == "train_bert.py" and "arch" not in cfg:
        args.append("--arch postln")                                 # runs from before --arch existed
    return f"python {SCRIPT[track]} {' '.join(args)} --out {out}"


def main():
    os.makedirs(OUT, exist_ok=True)
    stages = {k: [] for k in ("1_trackA", "2_trackC_lr", "3_trackB", "4_trackC", "5_random_replay",
                              "6_finetune", "7_postln_edge")}
    skipped = []
    for track in SCRIPT:
        for d in sorted(glob.glob(os.path.join(ROOT, "results", track, "*"))):
            name = os.path.basename(d)
            cf, ff = os.path.join(d, "config.json"), os.path.join(d, "final.json")
            edge = track == "trackC_edge"
            if not os.path.exists(cf) or (not edge and not os.path.exists(ff)):
                continue
            if "warm10" in name:
                skipped.append(name)
                continue
            cmd = cli(json.load(open(cf)), track, os.path.relpath(d, ROOT))
            if edge and "--stop_at" not in cmd:     # these runs were stopped by hand at ~6.5-7k steps
                cmd = cmd.replace(" --out ", " --stop_at 7000 --out ")
            line = f"{name} | {cmd}"
            if "random" in name:
                stage = "5_random_replay"
            elif track == "trackA":
                stage = "1_trackA"
            elif track in ("trackC_lr", "trackC_sweep"):
                stage = "2_trackC_lr"
            elif track == "trackB":
                stage = "3_trackB"
            elif track == "trackC":
                stage = "4_trackC"
            elif track in ("trackC_ft", "trackC_pub"):
                stage = "6_finetune"
            else:
                stage = "7_postln_edge"
            stages[stage].append(line)
    for stage, lines in stages.items():
        with open(os.path.join(OUT, f"{stage}.txt"), "w") as f:
            f.write(f"# {stage}: {len(lines)} runs, regenerated from results/*/config.json\n")
            f.write("\n".join(lines) + "\n")
        print(f"{stage}: {len(lines)} runs")
    print("skipped (bugged warm-start runs):", skipped)


if __name__ == "__main__":
    main()
